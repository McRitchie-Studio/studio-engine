# frozen_string_literal: true

require "fileutils"
require "pathname"

module Studio
  # Points a host's Tailwind entry for this engine at host.css.
  #
  # tailwindcss-rails' engines contract (Tailwindcss::Engines.bundle, run by
  # `tailwindcss:engines`, a prerequisite of tailwindcss:build, :watch and so
  # of assets:precompile) writes app/assets/builds/tailwind/studio_engine.css as
  # an @import of the gem's app/assets/tailwind/studio_engine/engine.css. That
  # file has to stay the NARROW component layer, because a build may import it
  # by path and want only the classes it names (the hub's client kit, held to a
  # 100 KB budget). So right after the bundle runs, this rewrites the entry to
  # import host.css instead: engine.css plus the engine's @source scan and the
  # motion layer. A host's `@import "../builds/tailwind/studio_engine";` then
  # brings all three, with no `@config`, no safelist and no rake task of its
  # own, and the gem's path is resolved here in Ruby, never by Node running
  # bundler.
  #
  # Prepended rather than added as a rake action: a second action on
  # `tailwindcss:engines` runs in task-load order, and one that ran BEFORE the
  # bundle would be deleted by it (the bundle removes and rewrites the file).
  # super-then-write is ordered by construction.
  module TailwindEntry
    HOST_CSS = "app/assets/tailwind/studio_engine/host.css"
    ENTRY    = "app/assets/builds/tailwind/studio_engine.css"

    module_function

    def entry_path(app_root) = Pathname(app_root).join(ENTRY)

    def contents(engine_root)
      <<~CSS
        /* DO NOT MODIFY THIS FILE, it was auto-generated by studio-engine (Studio::TailwindEntry) */

        @import "#{Pathname(engine_root).join(HOST_CSS)}";
      CSS
    end

    # Writes the entry. Only when the bundle wrote one: an app whose engines
    # contract found no engine.css gets nothing it did not ask for.
    def write!(app_root:, engine_root:)
      path = entry_path(app_root)
      return false unless path.file?

      File.write(path, contents(engine_root))
      true
    end

    # Wraps Tailwindcss::Engines.bundle.
    module Bundle
      def bundle(...)
        result = super
        Studio::TailwindEntry.write!(app_root: Rails.root, engine_root: Studio::Engine.root)
        result
      end
    end

    # Idempotent. A host without tailwindcss-rails' engines contract is left
    # alone: it never had the entry this rewrites.
    def install!
      require "tailwindcss/engines"
      singleton = ::Tailwindcss::Engines.singleton_class
      singleton.prepend(Bundle) unless singleton.ancestors.include?(Bundle)
      true
    rescue LoadError
      false
    end
  end
end
